"""The suite file: every test case to run, with its messages and its oracle (ADR 0053).

``modelbump suite PATH`` writes it, ``modelbump test SUITE`` reads it. The
file is plain JSON, so a developer can read it, edit it and commit it, and a
run always uses exactly the cases in the file.
"""

import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from modelbump.oracles import OracleChoice, OutputKind, choose_oracle
from modelbump.synth.cases import CaseResult, TestCase

SUITE_VERSION = 1
FIXED_SOURCE = "fixed prompt in the code"


@dataclass(frozen=True, slots=True)
class SuiteCase:
    """One test case: messages to send, and how to check the answers."""

    id: str
    """``support.py:24#2``: the call site and the case's number there."""
    path: str
    line: int
    api: str
    app_model: str | None
    """The model the app's code names; the test sends to ``--from``/``--to`` instead."""
    oracle: OracleChoice
    source: str
    """Where the inputs came from: ``tests/test_support.py:16`` or ``generated by ...``."""
    generated_by: str | None
    messages: tuple[tuple[str, str], ...]
    """``(role, text)``, ready to send."""

    @property
    def prompt(self) -> str:
        """All message text, for oracle checks that read the prompt (a word limit)."""
        return "\n".join(text for _, text in self.messages)


@dataclass(frozen=True, slots=True)
class Suite:
    """The cases to run and the calls that got none, with the reason."""

    cases: tuple[SuiteCase, ...]
    left_out: tuple[tuple[str, str], ...] = ()
    """``(path:line, reason)`` for each call with no case in the suite."""


def build_suite(result: CaseResult) -> Suite:
    """Every complete case of every call, except tool calls, with its oracle.

    A call whose prompt is all written text, with no slots, is one case as it is.
    """
    cases: list[SuiteCase] = []
    left_out: list[tuple[str, str]] = []
    for entry in result.sites:
        site = entry.site
        where = f"{site.path}:{site.line}"
        choice = choose_oracle(site)
        complete = [case for case in entry.cases if case.complete]
        if not complete and site.complete and not site.slots:
            # A fixed prompt needs no inputs: it is its own test case.
            complete = [TestCase(site, FIXED_SOURCE, ())]
        if choice.kind is OutputKind.TOOLS:
            left_out.append((where, "tool calls are not scored yet"))
            continue
        if not complete:
            reason = "no complete test case" if site.parts else "no prompt argument"
            left_out.append((where, reason))
            continue
        for number, case in enumerate(complete, start=1):
            cases.append(
                SuiteCase(
                    id=f"{where}#{number}",
                    path=site.path,
                    line=site.line,
                    api=site.api.value,
                    app_model=site.model,
                    oracle=choice,
                    source=case.source,
                    generated_by=case.generated_by,
                    messages=case.messages,
                )
            )
    return Suite(tuple(cases), tuple(left_out))


def suite_to_json(suite: Suite) -> str:
    """The suite file's text."""
    data = {
        "version": SUITE_VERSION,
        "cases": [
            {
                "id": case.id,
                "path": case.path,
                "line": case.line,
                "api": case.api,
                "app_model": case.app_model,
                "oracle": {
                    "kind": case.oracle.kind.value,
                    "reason": case.oracle.reason,
                    "labels": list(case.oracle.labels),
                },
                "source": case.source,
                "generated_by": case.generated_by,
                "messages": [{"role": role, "content": text} for role, text in case.messages],
            }
            for case in suite.cases
        ],
        "left_out": [{"call": where, "reason": reason} for where, reason in suite.left_out],
    }
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def _case(item: Any) -> SuiteCase:
    oracle = item["oracle"]
    kind = OutputKind(oracle["kind"])
    if kind is OutputKind.TOOLS:
        raise ValueError(f"case {item['id']}: tool calls are not scored yet")
    labels = tuple(str(label) for label in oracle.get("labels", []))
    if kind is OutputKind.LABEL and len(labels) < 2:
        raise ValueError(f"case {item['id']}: a label oracle needs at least two labels")
    messages = tuple((str(m["role"]), str(m["content"])) for m in item["messages"])
    if not messages:
        raise ValueError(f"case {item['id']}: no messages")
    return SuiteCase(
        id=str(item["id"]),
        path=str(item["path"]),
        line=int(item["line"]),
        api=str(item["api"]),
        app_model=item.get("app_model"),
        oracle=OracleChoice(kind, str(oracle.get("reason", "")), labels),
        source=str(item.get("source", "")),
        generated_by=item.get("generated_by"),
        messages=messages,
    )


def read_suite(path: Path) -> Suite:
    """Read a suite file. Raises ``ValueError`` with a readable message if it is wrong."""
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as error:
        raise ValueError(f"{path} is not valid JSON: {error}") from error
    if not isinstance(data, dict) or data.get("version") != SUITE_VERSION:
        raise ValueError(f"{path} is not a version {SUITE_VERSION} suite file")
    try:
        cases = tuple(_case(item) for item in data["cases"])
        left_out = tuple(
            (str(item["call"]), str(item["reason"])) for item in data.get("left_out", [])
        )
    except (KeyError, TypeError) as error:
        raise ValueError(f"{path}: a case is missing a field ({error})") from error
    ids = [case.id for case in cases]
    if len(set(ids)) != len(ids):
        raise ValueError(f"{path}: two cases share an id")
    return Suite(cases, left_out)
