"""Tests for generated test inputs (ADR 0051), with a fake model server."""

import asyncio
import json
from collections.abc import Callable
from pathlib import Path

import httpx
import pytest

from modelbump.runner import Runner
from modelbump.synth import CallSite, extract_calls
from modelbump.synth.cases import CaseResult, SiteCases, TestCase, find_cases
from modelbump.synth.generate import (
    DEFAULT_GENERATOR,
    MAX_ROUNDS,
    add_generated,
    fill,
    generation_request,
    needs_inputs,
    parse_values,
)

APP = (
    "def classify(client, ticket):\n"
    '    return client.chat.completions.create(model="gpt-4o-mini", messages=[\n'
    '        {"role": "system",\n'
    '         "content": "Answer bug or feature. Reply as {\\"label\\": ...}."},\n'
    '        {"role": "user", "content": f"Ticket: {ticket}"},\n'
    "    ])\n"
)


def site_of(source: str = APP) -> CallSite:
    (site,) = extract_calls("app.py", source)
    return site


Handler = Callable[[dict[str, object]], str]


def fake_runner(answer: Handler, seen: list[dict[str, object]]) -> Runner:
    def server(request: httpx.Request) -> httpx.Response:
        body = json.loads(request.content)
        seen.append(body)
        text = answer(body)
        if text == "ERROR":
            return httpx.Response(400, json={"error": {"message": "bad request"}})
        return httpx.Response(
            200,
            json={
                "choices": [{"message": {"content": text}, "finish_reason": "stop"}],
                "usage": {"prompt_tokens": 100, "completion_tokens": 50},
            },
        )

    return Runner(transport=httpx.MockTransport(server), max_attempts=1)


def answer_with(*sets: dict[str, object]) -> Handler:
    return lambda body: "Here you go:\n```json\n" + json.dumps(list(sets)) + "\n```"


# --- The request ---------------------------------------------------------------------


def test_the_request_shows_the_templates_and_asks_for_json() -> None:
    request = generation_request(site_of(), 3, DEFAULT_GENERATOR, sample=2)
    system, user = request.messages
    assert system.role == "system"
    assert "JSON only" in system.content
    assert "(openai_chat, model gpt-4o-mini), from app.py:2" in user.content
    assert "--- user message ---\nTicket: {ticket}" in user.content
    assert 'Answer bug or feature. Reply as {{"label": ...}}.' in user.content
    assert "Write 3 different sets of values for the slots ticket." in user.content
    assert 'exactly the keys ["ticket"]' in user.content
    assert (request.model, request.seed, request.sample) == (DEFAULT_GENERATOR, 2, 2)
    assert request.temperature == 0.8
    assert request.max_tokens == 750


# --- Reading the answer --------------------------------------------------------------


@pytest.mark.parametrize(
    ("text", "values"),
    [
        ('[{"a": "x", "b": "y"}]', [{"a": "x", "b": "y"}]),
        ('Sure!\n```json\n[{"a": "x", "b": "y", "extra": 1}]\n```', [{"a": "x", "b": "y"}]),
        (
            '[{"a": 3, "b": true}, {"a": 1.5, "b": false}]',
            [{"a": "3", "b": "true"}, {"a": "1.5", "b": "false"}],
        ),
        (
            '[{"a": "x"}, {"a": "x", "b": ["list"]}, "text", {"a": "ok", "b": "ok"}]',
            [{"a": "ok", "b": "ok"}],
        ),
        ('{"a": "x", "b": "y"}', []),
        ("[not json]", []),
        ("no array here", []),
        ('[{"a": "x", "b": "y"}', []),
    ],
)
def test_parse_values(text: str, values: list[dict[str, str]]) -> None:
    assert parse_values(text, ["a", "b"]) == values


def test_fill_keeps_braces_in_values_literal() -> None:
    filled = fill(site_of(), {"ticket": "Error {code} in {{x}}"})
    assert filled.parts[1].template == "Ticket: Error {{code}} in {{{{x}}}}"
    case = TestCase(filled, "generated", (("ticket", "x"),), generated_by="m")
    assert case.complete
    assert case.messages[1] == ("user", "Ticket: Error {code} in {{x}}")


# --- Adding generated cases ----------------------------------------------------------


def result_with(*entries: SiteCases) -> CaseResult:
    return CaseResult(entries, 1)


def test_cases_are_added_up_to_the_count_and_marked() -> None:
    seen: list[dict[str, object]] = []
    runner = fake_runner(answer_with({"ticket": "A"}, {"ticket": "B"}, {"ticket": "C"}), seen)
    done = asyncio.run(add_generated(result_with(SiteCases(site_of(), ())), runner, 2))
    (entry,) = done.result.sites
    assert [case.values for case in entry.cases] == [(("ticket", "A"),), (("ticket", "B"),)]
    assert all(case.generated_by == DEFAULT_GENERATOR for case in entry.cases)
    assert entry.cases[0].source == f"generated by {DEFAULT_GENERATOR}, sample 0"
    assert entry.cases[0].messages[1] == ("user", "Ticket: A")
    assert (done.asked, done.added, done.skipped) == (1, 2, ())
    assert len(seen) == 1
    assert seen[0]["seed"] == 0


def test_cases_from_the_code_count_toward_the_number() -> None:
    site = site_of()
    code_case = TestCase(fill(site, {"ticket": "From a test"}), "t.py:3", (("ticket", "x"),))
    seen: list[dict[str, object]] = []
    runner = fake_runner(answer_with({"ticket": "A"}, {"ticket": "B"}), seen)
    entry = SiteCases(site, (code_case,))
    done = asyncio.run(add_generated(result_with(entry), runner, 2))
    assert [c.generated_by for c in done.result.sites[0].cases] == [None, DEFAULT_GENERATOR]
    assert "Write 1 different sets" in str(seen[0]["messages"])
    enough = asyncio.run(add_generated(result_with(entry), runner, 1))
    assert (enough.asked, len(seen)) == (0, 1)


def test_duplicates_ask_again_with_the_next_sample() -> None:
    seen: list[dict[str, object]] = []

    def answer(body: dict[str, object]) -> str:
        return json.dumps(
            [{"ticket": "Same"}, {"ticket": "Same"}] if body["seed"] == 0 else [{"ticket": "New"}]
        )

    runner = fake_runner(answer, seen)
    done = asyncio.run(add_generated(result_with(SiteCases(site_of(), ())), runner, 2))
    assert [c.values[0][1] for c in done.result.sites[0].cases] == ["Same", "New"]
    assert [body["seed"] for body in seen] == [0, 1]
    assert done.result.sites[0].cases[1].source.endswith("sample 1")


def test_too_few_answers_after_every_round_are_reported() -> None:
    seen: list[dict[str, object]] = []
    runner = fake_runner(lambda body: "I cannot do that.", seen)
    done = asyncio.run(add_generated(result_with(SiteCases(site_of(), ())), runner, 2))
    assert len(seen) == MAX_ROUNDS
    ((site, reason),) = done.skipped
    assert site.line == 2
    assert reason == "2 fewer than asked: the answers had too few usable value sets"


def test_a_failed_call_is_reported_and_the_others_go_on() -> None:
    seen: list[dict[str, object]] = []
    other = site_of(APP.replace("gpt-4o-mini", "o3-mini"))

    def answer(body: dict[str, object]) -> str:
        return "ERROR" if "gpt-4o-mini" in str(body["messages"]) else json.dumps([{"ticket": "A"}])

    runner = fake_runner(answer, seen)
    done = asyncio.run(
        add_generated(result_with(SiteCases(site_of(), ()), SiteCases(other, ())), runner, 1)
    )
    assert [len(entry.cases) for entry in done.result.sites] == [0, 1]
    ((_, reason),) = done.skipped
    assert reason.startswith("the model call failed: ")


def test_calls_without_slots_or_with_unreadable_messages_are_not_asked(tmp_path: Path) -> None:
    (tmp_path / "app.py").write_text(
        "def a(client):\n"
        '    return client.completions.create(model="m", prompt="Fixed")\n'
        "def b(client, history, q):\n"
        '    return client.chat.completions.create(model="m", messages=history + '
        '[{"role": "user", "content": q}])\n'
    )
    result = find_cases(tmp_path)
    assert [needs_inputs(entry, 3) for entry in result.sites] == [False, False]
    seen: list[dict[str, object]] = []
    done = asyncio.run(add_generated(result, fake_runner(answer_with(), seen), 3))
    assert (done.asked, seen) == (0, [])


def test_another_writer_model_is_asked_by_its_name() -> None:
    seen: list[dict[str, object]] = []
    runner = fake_runner(answer_with({"ticket": "A"}), seen)
    asyncio.run(add_generated(result_with(SiteCases(site_of(), ())), runner, 1, "ollama/x", "abc"))
    assert seen[0]["model"] == "x"
