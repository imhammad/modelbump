FIX = "Reply with the label only."


def fake_runner() -> tuple[Runner, list[dict[str, Any]]]:
    """test_corpus_run's models, plus a proposer.

    The new model gets the ticket label wrong unless its system message says
    "label only". The evidence proposer (it sees failing answers) and the
    iterative one after its first round write that fix; the naive one and the
    iterative first round write a change that does nothing.
    """
    seen: list[dict[str, Any]] = []

    def server(request: httpx.Request) -> httpx.Response:
        body = json.loads(request.content)
        seen.append(body)
        system = body["messages"][0]["content"]
        prompt = body["messages"][-1]["content"]
        if system.startswith("You fix prompts"):
            fixes = "they fail" in prompt or "Changes tried so far" in prompt
            add = FIX if fixes else "Be brief."
            text = json.dumps({"add_system": add, "edits": [], "why": "w"})
        elif system.startswith("You write test inputs"):
            slots = json.loads(prompt.split("exactly the keys ")[1].split(", and every")[0])
            text = json.dumps(
                [{slot: f"value {body.get('seed', 0)}-{n}" for slot in slots} for n in (1, 2)]
            )
        elif system.startswith("You grade"):
            text = "PASS"
        elif "billing, bug or other" in system:
            wrong = "qwen3" in body["model"] and "label only" not in system
            text = "other" if wrong else "bug"
        elif "JSON" in prompt:
            text = '{"summary": "ok"}'
        else:
            text = f"Rain falls softly, number {body.get('seed', 0)}."
        return httpx.Response(
            200,
            json={
                "choices": [{"message": {"content": text}, "finish_reason": "stop"}],
                "usage": {"prompt_tokens": 10, "completion_tokens": 5},
            },
        )

    return Runner(transport=httpx.MockTransport(server)), seen


def corpus_run(tmp_path: Path) -> tuple[Path, Path, Runner, list[dict[str, Any]]]:
    corpus = write_corpus(tmp_path)
    apps = [json.loads(line) for line in (corpus / "apps.jsonl").read_text().splitlines()]
    runner, seen = fake_runner()
    run_dir = tmp_path / "run-v3"
    asyncio.run(run_corpus(apps, runner, SETTINGS, run_dir, calls=3, seed=1))
    return corpus, run_dir, runner, seen


def test_regressed_calls_and_widen(tmp_path: Path) -> None:
    _corpus, run_dir, runner, _seen = corpus_run(tmp_path)
    report = json.loads((run_dir / "runs" / "app-01.report.json").read_text())
    suite = read_suite(run_dir / "runs" / "app-01.suite.json")
    (case,) = regressed_calls(report, suite)
    assert case.id == "app.py:7#1"
    folder = tmp_path / "apps" / "1"
    widened = asyncio.run(widen(case, folder, runner, 2, "ollama/qwen2.5:7b"))
    assert [c.id for c in widened.cases] == ["app.py:7#1", "app.py:7#2", "app.py:7#3"]
    assert widened.cases[0] == case
    assert widened.cases[1].messages[-1][1] == "Ticket: value 100-1"
    assert widened.cases[2].source == "generated by ollama/qwen2.5:7b, sample 100"
    assert asyncio.run(widen(case, folder, runner, 0, "g")).cases == (case,)
    # A call that is not in the folder any more keeps its one case.
    assert asyncio.run(widen(case, tmp_path / "apps" / "2", runner, 2, "g")).cases == (case,)


def test_counted_tallies_by_role_and_undoes(tmp_path: Path) -> None:
    runner, _ = fake_runner()
    tally = Tally()
    original = runner.run_each
    undo = counted(runner, tally, {"ollama/a": "old", "ollama/g": "judge"})
    proposal = ChatRequest.ask("ollama/g", "fix it", system=PROPOSER_SYSTEM)
    asyncio.run(
        runner.run_each(
            [ChatRequest.ask("ollama/a", "hi"), ChatRequest.ask("ollama/b", "x"), proposal]
        )
    )
    # The proposer is told apart from the judge although both are ollama/g.
    assert tally.requests == {"old": 1, "other": 1, "proposer": 1}
    assert tally.fresh == {"old": 1, "other": 1, "proposer": 1}
    assert tally.tokens["old"] == 5
    undo()
    assert runner.run_each == original


def test_blocked_for_collateral() -> None:
    def repair(*checks: CaseCheck) -> CallRepair:
        return CallRepair("a.py:1", ("a.py:1#1",), 2, 1.0, 0.0, (), (Confirmation("f", checks),))

    ok = CaseCheck("a.py:1#1", 100, 100, 100, 0.0, True)
    broke = CaseCheck("a.py:1#2", 100, 10, 100, -0.9, False)
    not_fixed = CaseCheck("a.py:1#1", 100, 10, 100, -0.9, False)
    fine = CaseCheck("a.py:1#2", 100, 100, 100, 0.0, True)
    assert blocked_for_collateral(repair(ok, broke))
    assert not blocked_for_collateral(repair(not_fixed, fine))
    assert not blocked_for_collateral(repair(not_fixed, broke))
    assert not blocked_for_collateral(repair(ok, fine))  # accepted


def test_wilson() -> None:
    assert wilson(0, 0) == (0.0, 1.0)
    low, high = wilson(5, 10)
    assert low == pytest.approx(0.2366, abs=1e-3) and high == pytest.approx(0.7634, abs=1e-3)


def test_main_runs_every_strategy(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    corpus, run_dir, runner, _seen = corpus_run(tmp_path)
    out = tmp_path / "eval"
    args = ["--corpus", str(corpus), "--run", str(run_dir), "--out", str(out)]
    assert main(args, runner=runner) == 0
    printed = capsys.readouterr()
    rows = [json.loads(line) for line in (out / "results.jsonl").read_text().splitlines()]
    assert [(r["strategy"], r["status"]) for r in rows] == [
        ("evidence", "REPAIRED"),
        ("naive", "SKIPPED"),
        ("iterative", "REPAIRED"),
    ]
    evidence = rows[0]
    assert (evidence["migration"], evidence["app"], evidence["call"]) == (
        "run-v3",
        "app-01",
        "app.py:7",
    )
    assert (evidence["cases"], evidence["kind"]) == (3, "label")
    assert evidence["requests"]["proposer"] == 5
    assert evidence["requests"]["new"] > 0 and evidence["fresh"]["new"] > 0
    iterative = rows[2]
    assert iterative["requests"]["proposer"] == 6
    summary = json.loads((out / "summary.json").read_text())
    assert summary["calls"] == 1 and summary["calls_repaired_by_any"] == 1
    assert summary["strategies"]["evidence"]["fix_rate"] == 1.0
    assert summary["strategies"]["naive"]["outcomes"] == {"SKIPPED": 1}
    assert "evidence   1/1 repaired (100%" in printed.out
    folder = out / "run-v3" / "app-01" / "app.py-7"
    assert (folder / "suite-report.json").exists()
    assert (
        json.loads((folder / "evidence" / "repair-report.json").read_text())["calls"][0]["status"]
        == "REPAIRED"
    )
    assert (folder / "naive" / "proposals.json").exists()
    assert "run-v3 app-01/app.py:7 [naive]: SKIPPED" in printed.err


def test_main_options_and_errors(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    assert main(["--corpus", str(tmp_path / "none")]) == 1
    corpus, run_dir, runner, _ = corpus_run(tmp_path)
    assert main(["--corpus", str(corpus), "--run", str(tmp_path / "missing")]) == 1
    assert "No corpus run in" in capsys.readouterr().err
    out = tmp_path / "eval"
    base = ["--corpus", str(corpus), "--run", str(run_dir), "--out", str(out)]
    assert main([*base, "--drop-call", "app-01/app.py:7"], runner=runner) == 0
    summary = json.loads((out / "summary.json").read_text())
    assert summary["calls"] == 0
    assert summary["notes"] == [
        {"migration": "run-v3", "call": "app-01/app.py:7", "note": "dropped by hand"}
    ]
    assert main([*base, "--calls", "0"], runner=runner) == 0
    assert main([*base, "--strategy", "naive", "--extra", "0"], runner=runner) == 0
    rows = [json.loads(line) for line in (out / "results.jsonl").read_text().splitlines()]
    assert [(r["strategy"], r["cases"]) for r in rows] == [("naive", 1)]


